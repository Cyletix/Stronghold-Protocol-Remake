'use strict';
const assert=require('node:assert/strict'),pairs=require('../web/src/simulation/paired-battle');
const roster=Array.from({length:4},(_,i)=>({id:'p'+(i+1),life:20,units:[]}));
for(let count=1;count<=4;count++){
  const players=roster.slice(0,count),plan=pairs.pairAlivePlayers(players,{seed:1221,round:14});
  assert.equal(plan.groups.length,Math.ceil(count/2));assert.ok(plan.groups.every(g=>g.seats.length<=2));
  assert.deepEqual(plan.groups.flatMap(g=>g.seats.map(s=>s.playerId)).sort(),players.map(p=>p.id));
  assert.deepEqual(plan,pairs.pairAlivePlayers([...players].reverse(),{seed:1221,round:14}));
  if(count%2)assert.deepEqual(plan.groups.at(-1).seats.map(s=>s.side),['left']);
}
const eliminated=roster.map(p=>({...p}));eliminated[0].life=0;eliminated[1].eliminated=true;eliminated[2].connected=false;
const remaining=pairs.pairAlivePlayers(eliminated,{seed:33,round:14});
assert.deepEqual(remaining.spectatorPlayerIds,['p1','p2']);assert.equal(remaining.groups[0].seats.length,2,'disconnect is not elimination');
assert.ok(pairs.viewingSeats(remaining,'p1').every(v=>!v.canControl&&v.side==='overview'));
assert.ok(pairs.viewingSeats(remaining,'p3').some(v=>v.canControl));
assert.equal(pairs.pairAlivePlayers(roster.map(p=>({...p,alive:false})),{seed:1,round:14}).groups.length,0);
assert.ok(new Set(Array.from({length:25},(_,seed)=>JSON.stringify(pairs.pairAlivePlayers(roster,{seed,round:14}).groups))).size>5,'seed controls pair and side assignment');
const boss={kind:'boss',rows:19,cols:25,left:{start:2,end:11},center:{start:11,end:16},right:{start:16,end:25}};
const joint={kind:'joint-defense',rows:19,cols:25,left:{start:2,end:11},right:{start:13,end:22}};
const left={playerId:'p1',side:'left'},right={playerId:'p2',side:'right'};
const unit={id:1,charId:'char-test',row:14,col:3,dir:'left',equip:[{uid:9,id:'item',mods:{atk:1.5}}]};
for(const layout of [boss,joint])for(const seat of [left,right])for(const dir of ['up','down','left','right']){
  const original={...unit,dir},world=pairs.toWorldUnit(original,seat,layout);
  assert.deepEqual(pairs.toLocalUnit(world,seat,layout),original);
  world.equip[0].mods.atk=99;assert.equal(unit.equip[0].mods.atk,1.5,'transform does not mutate inventory');
}
const bossRight=pairs.toWorldUnit(unit,right,boss),jointRight=pairs.toWorldUnit(unit,right,joint);
assert.equal(bossRight.col,23);assert.equal(bossRight.dir,'right');
assert.equal(jointRight.col,14);assert.equal(jointRight.dir,'left','joint defense translates formation without mirroring its direction');
const players=roster.map(p=>({...p,units:[structuredClone(unit)]}));
const group={id:'boss:14:0',kind:'boss',seats:[left,right]};
const input=pairs.buildBattleInput(group,players,boss,{isDeployable:(row,col)=>row===14&&![11,12,13,14,15].includes(col)});
assert.equal(input.units.length,2);assert.notEqual(input.units[0].id,input.units[1].id,'same numeric unit ID from two players cannot collide');
assert.equal(input.units[0].unitId,1);assert.equal(input.units[1].unitId,1);assert.deepEqual(input.observerPlayerIds,['p3','p4']);
assert.equal(input.topology,'symmetric-center');
assert.equal(pairs.buildBattleInput({...group,kind:'joint-defense'},players,joint).topology,'right-to-left');
const jointGroup={...group,kind:'joint-defense'},results=players.map(p=>({...p,leakCount:0}));
assert.deepEqual(pairs.jointDefenseGroup(jointGroup,results).seats,[left,right]);
results[0].leakCount=1;assert.deepEqual(pairs.jointDefenseGroup(jointGroup,results).seats,[{playerId:'p2',side:'left'}]);
results[1].leakCount=1;assert.equal(pairs.jointDefenseGroup(jointGroup,results),null);
const rejects=(fn,code)=>assert.throws(fn,error=>error.code===code);
rejects(()=>pairs.jointDefenseGroup(group,results),'INVALID_KIND');
rejects(()=>pairs.jointDefenseGroup(jointGroup,players),'INVALID_RESULT');
rejects(()=>pairs.pairAlivePlayers([roster[0],roster[0]],{seed:1,round:1}),'DUPLICATE_PLAYER');
rejects(()=>pairs.pairAlivePlayers([...roster,{id:'p5'}],{seed:1,round:1}),'INVALID_PLAYERS');
rejects(()=>pairs.pairAlivePlayers(roster,{round:1}),'INVALID_SEED');
rejects(()=>pairs.pairAlivePlayers(roster,{seed:1,round:1,kind:'normal'}),'INVALID_KIND');
rejects(()=>pairs.toWorldUnit({...unit,col:11},right,boss),'INVALID_CELL');
rejects(()=>pairs.toWorldUnit({...unit,row:19},right,boss),'INVALID_CELL');
rejects(()=>pairs.toWorldUnit({...unit,dir:'north'},right,boss),'INVALID_DIRECTION');
rejects(()=>pairs.toWorldUnit({...unit,playerId:'p1'},right,boss),'INVALID_UNIT');
rejects(()=>pairs.toLocalUnit(bossRight,left,boss),'OWNER_MISMATCH');
rejects(()=>pairs.buildBattleInput(group,players,joint),'INVALID_LAYOUT');
rejects(()=>pairs.buildBattleInput({...group,seats:[left,left]},players,boss),'INVALID_GROUP');
rejects(()=>pairs.buildBattleInput(group,[{...players[0],life:0},players[1]],boss),'INACTIVE_PLAYER');
rejects(()=>pairs.buildBattleInput(group,players,boss,{isDeployable:()=>false}),'INVALID_CELL');
rejects(()=>pairs.buildBattleInput(group,[{...players[0],units:[unit,{...unit,id:2}]},players[1]],boss),'COLLISION');
rejects(()=>pairs.buildBattleInput(group,[{...players[0],units:[unit,unit]},players[1]],boss),'DUPLICATE_UNIT');
rejects(()=>pairs.buildBattleInput(group,players,{...boss,center:{start:11,end:15}}),'INVALID_LAYOUT');
const reserve=pairs.buildBattleInput(group,[{...players[0],units:[{...unit,row:null,col:null}]},players[1]],boss);assert.equal(reserve.units.length,1);
assert.deepEqual(unit,{id:1,charId:'char-test',row:14,col:3,dir:'left',equip:[{uid:9,id:'item',mods:{atk:1.5}}]});
console.log('PAIRED BATTLE OK 1-4 living players, deterministic pairs, elimination/spectating, separate boss/joint topologies, owned IDs, reversible formation/equipment and invalid-input guards');
