'use strict';
const assert=require('node:assert/strict'),{create,describe}=require('../web/src/ui/phase-notice');
const tracker=create(),game=(phase,round=1,kind='normal')=>({phase,players:[{round},{round}],battles:[{kind}]});
assert.equal(tracker.next(game('preparing'),1).kind,'prepare');
assert.equal(tracker.next(game('preparing'),1),null);
assert.equal(tracker.next({...game('preparing'),viewPlayerId:'other'},1),null,'changing the viewed player does not announce a new phase');
assert.equal(tracker.next(game('battle'),1).kind,'battle');
assert.equal(tracker.next(game('battle'),1),null);
assert.equal(tracker.next(game('battle',1,'joint-defense'),1).kind,'joint','joint defense starts within the same battle phase');
assert.equal(tracker.next(game('battle',1,'joint-defense'),1),null);
assert.equal(tracker.next(game('intermission'),1).kind,'end');
assert.equal(tracker.next(game('preparing',2),1).kind,'prepare');
assert.equal(tracker.next(game('battle',14,'boss'),1).kind,'boss');
assert.equal(tracker.next(game('over',14),1),null);
tracker.reset();assert.equal(tracker.next(game('battle',14,'boss'),1),null,'refreshing ongoing battle cannot falsely replay its start');
assert.equal(tracker.next(game('battle',14,'boss'),1),null);
assert.equal(tracker.next(game('preparing',15),1).round,15);
tracker.reset();assert.equal(tracker.next(game('preparing'),2).kind,'prepare','a new run gets a fresh intro');
assert.equal(describe({phase:'preparing',players:[{round:1,eliminated:true},{round:8}],battles:[]}).round,8,'old eliminated player cannot move the phase backwards');
assert.equal(describe({phase:'preparing',players:[]}),null);
console.log('PHASE NOTICE OK: prepare, battle, joint defense, boss, end; repeated packets/view changes/reloads/new runs');
