'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),crypto=require('crypto');
const root=path.join(__dirname,'..'),source='data/ArknightsGameData/zh_CN/gamedata/excel/skill_table.json';
const raw=fs.readFileSync(path.join(root,source),'utf8'),skills=JSON.parse(raw),{extractLevel}=require('./extract_skills');
const ctx={window:{}};vm.runInNewContext(fs.readFileSync(path.join(root,'web/src/simulation/common-skills.js'),'utf8'),ctx);
const data={version:1,source,sha256:crypto.createHash('sha256').update(raw).digest('hex'),skillLevels:{}};
for(const id of ctx.window.ArkCommonSkills.supported){
 if(!skills[id]?.levels?.length)throw Error('Missing common skill '+id);
 data.skillLevels[id]=skills[id].levels.map((lv,i)=>{
  const s={...extractLevel(skills[id],i),isPassive:lv.skillType==='PASSIVE'};
  ctx.window.ArkCommonSkills.configure({...s,sourceId:id});return s;
 });
}
const out='// Generated by tools/build_common_skill_data.js; source values only.\nwindow.ArkCommonSkillData='+JSON.stringify(data)+';\n';
const target=path.join(root,'web/common_skill_data.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==out)throw Error('common_skill_data.js drift');}else fs.writeFileSync(target,out);
console.log('COMMON SKILL DATA OK '+Object.keys(data.skillLevels).length+' IDs, '+Object.values(data.skillLevels).reduce((n,a)=>n+a.length,0)+' source levels');
