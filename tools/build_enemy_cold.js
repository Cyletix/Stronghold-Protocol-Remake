'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..'),files={enemies:'data/ArknightsGameData/zh_CN/gamedata/levels/enemydata/enemy_database.json',buffs:'data/ArknightsGameData/zh_CN/gamedata/buff_table.json',handbook:'data/ArknightsGameData/zh_CN/gamedata/excel/enemy_handbook_table.json'};
const read=f=>JSON.parse(fs.readFileSync(path.join(root,f),'utf8'));
const db=read(files.enemies),buffs=read(files.buffs),handbook=read(files.handbook).enemyData,{enemyVariant}=require('./lib/source-battle');
const data={version:1,sources:Object.fromEntries(Object.entries(files).map(([k,f])=>[k,{path:f,sha256:crypto.createHash('sha256').update(fs.readFileSync(path.join(root,f))).digest('hex')}])),
  coldAspd:buffs.e2c_cold.attributes.attributeModifiers.find(x=>x.attributeType==='ATTACK_SPEED').value/100,
  // Geometry/timing are community research, not the enemy's melee rangeRadius.
  deathBlast:{radius:1.65,delay:1,source:'https://prts.wiki/w/冰爆源石虫'},enemies:{}};
for(const id of ['enemy_1067_snslime','enemy_1069_icebrk','enemy_1069_icebrk_2']){
  const v=enemyVariant({id,level:0,useDb:true},new Map(db.enemies.map(e=>[e.Key,e.Value])),{});
  if(!v?.sourceTalentBlackboard?.length)throw Error('Missing cold enemy blackboard '+id);
  if(handbook[id]?.damageType?.join()!=='PHYSIC')throw Error('Cold enemy damage type changed '+id);
  data.enemies[id]={kind:id==='enemy_1067_snslime'?'death-cold':'frozen-attack',blackboard:v.sourceTalentBlackboard,
    applyWay:v.applyWay,canAttack:v.canAttack,flying:v.flying,damageType:'phys'};
}
const out='// Generated by tools/build_enemy_cold.js; see docs/mechanics/enemy-cold.md.\nwindow.ArkEnemyColdData='+JSON.stringify(data,null,2)+';\n';
const target=path.join(root,'web/enemy_cold_data.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==out)throw Error('enemy_cold_data.js drift');}else fs.writeFileSync(target,out);
console.log('ENEMY COLD DATA OK: 3 explicit enemy profiles and e2c cold speed modifier');
