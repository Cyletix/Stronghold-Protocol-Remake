'use strict';
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.join(__dirname,'..'),prefix='data/ArknightsGameData/zh_CN/gamedata/excel/';
const files=[prefix+'character_table.json',prefix+'skill_table.json',prefix+'range_table.json','web/battle_levels.json'];
const [chars,skills,ranges,battle]=files.map(f=>JSON.parse(fs.readFileSync(path.join(root,f),'utf8')));
const {extractLevel}=require('./extract_skills');
const data={version:1,sources:Object.fromEntries(files.map(f=>[f,crypto.createHash('sha256').update(fs.readFileSync(path.join(root,f))).digest('hex')])),characters:{},skills:{}};
for(const o of battle.operators){
 if(!chars[o.charId])throw Error('Missing source character '+o.charId);
 data.characters[o.charId]=(chars[o.charId].skills||[]).map(s=>s.skillId).filter(Boolean);
}
let count=0;
for(const id of [...new Set(Object.values(data.characters).flat())].sort()){
 const source=skills[id];if(!source?.levels.length)throw Error('Missing skill '+id);
 let previous={};
 // Deltas include explicit nulls and refer to the PREVIOUS level.
 data.skills[id]=source.levels.map((raw,i)=>{
  if(raw.rangeId&&!ranges[raw.rangeId])throw Error('Missing range '+id+'/'+raw.rangeId);
  const lv={...extractLevel(source,i),isPassive:raw.skillType==='PASSIVE'},bb=lv.blackboard;
  lv.desc=raw.description.replace(/\{([^}:]+)(?::([^}]*))?\}/g,(m,key,format)=>{
   const negative=key.startsWith('-'),name=negative?key.slice(1):key;
   if(!(name in bb))return m;
   const percent=format?.includes('%'),value=bb[name]*(negative?-1:1)*(percent?100:1);
   return String(Math.round(value*100)/100)+(percent?'%':'');
  });
  const delta=Object.fromEntries(Object.entries(lv).filter(([k,v])=>JSON.stringify(v)!==JSON.stringify(previous[k])));
  previous=lv;count++;return delta;
 });
}
const out='// Generated by tools/build_operator_skill_levels.js; source levels, not execution coverage.\nwindow.ArkOperatorSkillData='+JSON.stringify(data)+';\n';
const target=path.join(root,'web/operator_skill_levels.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==out)throw Error('operator_skill_levels.js drift');}else fs.writeFileSync(target,out);
console.log('OPERATOR SKILL LEVELS OK '+Object.keys(data.characters).length+' identities, '+Object.keys(data.skills).length+' skills, '+count+' levels, '+Buffer.byteLength(out)+' bytes');
