function runChecks(list=checks,{report=console.log,timeout=120000}={}){
  const started=Date.now();
  for(const [name,args]of list){
    const result=spawnSync(process.execPath,['--unhandled-rejections=strict',...args],{cwd:root,encoding:'utf8',timeout,maxBuffer:6*1024*1024,windowsHide:true});
    if(result.error||result.signal||result.status!==0){
      report('FAIL '+name+'\n'+[result.error?.message,result.signal,result.stdout,result.stderr].filter(Boolean).join('\n'));
      return 1;
    }
    report('PASS '+name);
  }
  report('GAME CHECK OK '+list.length+' checks ('+((Date.now()-started)/1000).toFixed(1)+'s)');return 0;
}
if(require.main===module){
  const args=process.argv.slice(2);
  if(args.length===1&&args[0]==='--list')for(const [name,cmd]of checks)console.log(name+': node '+cmd.join(' '));
  else if(args.length){console.error('Usage: node tools/check_game.js [--list]');process.exitCode=2;}
  else process.exitCode=runChecks();
}
module.exports={checks,runChecks};
